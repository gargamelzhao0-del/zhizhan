"""Verify portable framing on this host and the CMake teaching project. No Linux/board claim."""
import hashlib
import importlib.util
import io
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import unittest
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parent.parent
report = {'platform': platform.platform(), 'linuxTargetTested': False, 'passed': False}
def command(args):
    result = subprocess.run([str(arg) for arg in args], capture_output=True, text=True, cwd=root, timeout=120)
    if result.returncode:
        raise RuntimeError(result.stdout + result.stderr)
    return result.stdout
try:
    source = root / 'content/examples/linux/tcp_frames.py'
    spec = importlib.util.spec_from_file_location('framing_lab', source)
    module = importlib.util.module_from_spec(spec)
    # Avoid leaving generated bytecode beside source attachments.
    exec(compile(source.read_text(encoding='utf-8'), str(source), 'exec'), module.__dict__)
    output = io.StringIO()
    result = unittest.TextTestRunner(stream=output, verbosity=2).run(unittest.defaultTestLoader.loadTestsFromModule(module))
    report['tcpFramingTests'] = {'passed': result.wasSuccessful(), 'count': result.testsRun, 'output': output.getvalue(), 'network': '127.0.0.1 only'}
    if not result.wasSuccessful(): raise RuntimeError(output.getvalue())
    cmake = os.environ.get('CMAKE') or shutil.which('cmake')
    ninja = os.environ.get('NINJA') or shutil.which('ninja')
    compiler = os.environ.get('CXX') or shutil.which('g++')
    if not all((cmake, ninja, compiler)): raise RuntimeError('Set CMAKE, NINJA and CXX or provide these tools on PATH')
    build = root / 'build/cmake-lessons'
    command([cmake, '-S', 'content/examples/cpp', '-B', build, '-G', 'Ninja', '-DCMAKE_BUILD_TYPE=Debug',
             '-DCMAKE_MAKE_PROGRAM=' + ninja, '-DCMAKE_CXX_COMPILER=' + compiler])
    command([cmake, '--build', build, '--config', 'Debug'])
    ctest = Path(cmake).with_name('ctest.exe' if os.name == 'nt' else 'ctest')
    xml = build / 'test-results.xml'
    report['cmakeOutput'] = command([ctest, '--test-dir', build, '-C', 'Debug', '--output-on-failure', '--output-junit', xml])
    suite = ET.parse(xml).getroot()
    if int(suite.attrib.get('failures', 0)) or int(suite.attrib.get('tests', 0)) != 3: raise RuntimeError('CTest did not pass all 3 checks')
    report['cmakeTests'] = 3
    report['cmakeVersion'] = command([cmake, '--version']).splitlines()[0]
    sources = [source, root / 'content/examples/cpp/CMakeLists.txt'] + [root / ('content/examples/cpp/' + name) for name in ('07-project.cpp','08-ownership.cpp','09-algorithms.cpp','10-interfaces.cpp')]
    report['sources'] = [{'file': p.relative_to(root).as_posix(), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()} for p in sources]
    report['passed'] = True
finally:
    (root / 'docs/advanced-labs-validation.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps({'passed': True, 'framingTests': result.testsRun, 'cmakeTests': 3, 'linuxTargetTested': False}))
