// Load credentials only into memory. Reports and console output never contain them.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const profile = JSON.parse(await fs.readFile('.private/update-service.json','utf8'));
const metadata = JSON.parse(await fs.readFile('package.json','utf8'));
const remote = process.argv.includes('--remote');
const origin = remote ? new URL(profile.url).origin : 'http://127.0.0.1:8463';
const url = `${origin}/latest.json`;
const anonymous = await fetch(url, {signal:AbortSignal.timeout(25000)});
assert.equal(anonymous.status,401);
const headers = {Authorization:`Bearer ${profile.token}`, 'Accept-Encoding':'identity'};
const response = await fetch(url,{headers, signal:AbortSignal.timeout(45000)});
assert.equal(response.status,200);
const manifest = await response.json();
assert.equal(manifest.version,metadata.version);
assert.equal(manifest.versionCode,metadata.androidVersionCode);
const apkUrl = new URL(manifest.apk.url,url);
assert.equal(apkUrl.origin,origin);
const download = await fetch(apkUrl,{headers,signal:AbortSignal.timeout(120000)});
assert.equal(download.status,200);
const bytes = Buffer.from(await download.arrayBuffer());
const sha256 = createHash('sha256').update(bytes).digest('hex');
assert.equal(bytes.length,manifest.apk.bytes);
assert.equal(sha256,manifest.apk.sha256);
assert.equal(sha256,createHash('sha256').update(await fs.readFile(`release/zhizhan-${metadata.version}-android.apk`)).digest('hex'));
const result={passed:true,date:new Date().toISOString(),version:metadata.version,url,bytes:bytes.length,sha256,authenticated:true,anonymousStatus:401,publicHttpsVerified:remote,remotePhoneTested:false};
await fs.writeFile(`docs/${remote?'remote-service':'private-server'}-validation.json`,JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
